/**
 * Reproduce the published application snapshot without fetching or executing it.
 * The original TypeScript source was absent from GitHub. Keep this adapter
 * separate from authored code until the matching source is available.
 */
import ts from "typescript";
import { gunzipSync } from "node:zlib";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const snapshot = JSON.parse(gunzipSync(await readFile(join(here, "source.json.gz"))));
const manifest = JSON.parse(await readFile(join(here, "manifest.json"), "utf8"));
const scratch = join(root, "outputs/published-snapshot-source");
const target = join(root, "src/published-app");
const check = process.argv.includes("--check");
await mkdir(scratch, { recursive: true });
await mkdir(target, { recursive: true });

for (const [name, text] of Object.entries(snapshot.files)) {
  if (!/^[\w-]+\.(js|css)$/.test(name)) throw new Error(`Invalid module: ${name}`);
  const hash = createHash("sha256").update(text).digest("hex");
  if (hash !== manifest.modules.find((item) => item.name === name)?.sha256)
    throw new Error(`Source integrity failed: ${name}`);
  await writeFile(join(scratch, name), text);
}

const entryPath = join(scratch, manifest.entry);
const program = ts.createProgram([entryPath], {
  allowJs: true, checkJs: false, noResolve: true, target: ts.ScriptTarget.ESNext,
});
const source = program.getSourceFile(entryPath);
const checker = program.getTypeChecker();
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
const declarations = new Map();
const symbols = new Map();
for (const statement of source.statements) {
  const nodes = ts.isVariableStatement(statement)
    ? [...statement.declarationList.declarations]
    : ts.isFunctionDeclaration(statement) ? [statement] : [];
  for (const node of nodes) if (node.name && ts.isIdentifier(node.name)) {
    declarations.set(node.name.text, node);
    symbols.set(checker.getSymbolAtLocation(node.name), node.name.text);
  }
}
const exports = [];
for (const node of source.statements)
  if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause))
    for (const spec of node.exportClause.elements)
      exports.push({ local: spec.propertyName?.text || spec.name.text, exported: spec.name.text });

// Bind the published bundle's framework factories to the repository packages.
// All domain bindings and their dependent side effects remain in the snapshot.
const overrides = new Set(["u", "m", "Ee", "w", "N", "g"]);
const references = (node) => {
  const result = new Set();
  const visit = (child) => {
    if (ts.isIdentifier(child)) {
      const symbol = ts.isShorthandPropertyAssignment(child.parent)
        ? checker.getShorthandAssignmentValueSymbol(child.parent)
        : checker.getSymbolAtLocation(child);
      const name = symbols.get(symbol);
      if (name) result.add(name);
    }
    ts.forEachChild(child, visit);
  };
  visit(node);
  return result;
};
const needed = new Set(exports.map((item) => item.local).concat("Ft"));
const effects = new Set();
let changed = true;
while (changed) {
  changed = false;
  for (const name of [...needed]) if (!overrides.has(name)) {
    const declaration = declarations.get(name);
    if (!declaration) throw new Error(`Missing binding: ${name}`);
    for (const ref of references(declaration)) if (!needed.has(ref)) {
      needed.add(ref); changed = true;
    }
  }
  for (const node of source.statements) {
    if (ts.isVariableStatement(node) || ts.isFunctionDeclaration(node)
      || ts.isExportDeclaration(node) || ts.isImportDeclaration(node)) continue;
    const text = node.getText(source);
    // main.tsx owns mounting and worker registration in this checkout.
    if (text.includes("createRoot") || text.includes("serviceWorker")) continue;
    const refs = references(node);
    if ([...refs].some((name) => needed.has(name))) {
      effects.add(node);
      for (const name of refs) if (!needed.has(name)) {
        needed.add(name); changed = true;
      }
    }
  }
}
let entry = `// Generated by tools/published-snapshot/restore.mjs. See its README.\nimport __react from 'react';\nimport * as __reactDOM from 'react-dom';\nimport * as __reactDOMClient from 'react-dom/client';\nimport * as __jsxRuntime from 'react/jsx-runtime';\nimport {createLucideIcon as __createIcon} from 'lucide-react';\nimport './index-C08tv5ZB.css';\nconst u=()=>__react, m=()=>__reactDOM, g=()=>__reactDOMClient, Ee=()=>__jsxRuntime, w=__createIcon;\nconst N=(load)=>load();\n`;
for (const node of source.statements) {
  if (ts.isVariableStatement(node)) {
    const kept = node.declarationList.declarations.filter((d) =>
      ts.isIdentifier(d.name) && needed.has(d.name.text) && !overrides.has(d.name.text));
    if (kept.length) entry += printer.printNode(ts.EmitHint.Unspecified,
      ts.factory.createVariableStatement(undefined,
        ts.factory.createVariableDeclarationList(kept, node.declarationList.flags)), source) + "\n";
  } else if ((ts.isFunctionDeclaration(node) && needed.has(node.name?.text)
    && !overrides.has(node.name.text)) || effects.has(node))
    entry += printer.printNode(ts.EmitHint.Unspecified, node, source) + "\n";
}
entry += `export {${exports.map((item) => `${item.local} as ${item.exported}`).join(",")}, Ft as RecoveredApp};\n`;

const value = (node) => ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)
  ? node.text : undefined;
const property = (node, name) => node.properties.find((p) =>
  ts.isPropertyAssignment(p) && p.name.text === name);
const label = (node) => {
  if (!ts.isCallExpression(node) || !ts.isObjectLiteralExpression(node.arguments[1])) return;
  const attr = property(node.arguments[1], "aria-label");
  return attr && value(attr.initializer);
};
function groupZoomButtons(file) {
  let groups = 0;
  let photoHooks = 0;
  const result = ts.transform(file, [(context) => {
    const visit = (node) => {
      if (ts.isFunctionDeclaration(node) && node.name?.text === "I"
        && node.body?.getText(file).includes("Photo detail.")) {
        const visited = ts.visitEachChild(node, visit, context);
        const statements = [...visited.body.statements];
        const index = statements.findIndex((item) => ts.isReturnStatement(item));
        if (index < 0) throw new Error("Missing photo viewer return");
        statements.splice(index, 0, ts.factory.createExpressionStatement(
          ts.factory.createCallExpression(ts.factory.createIdentifier("__usePhotoWheelZoom"),
            undefined, ["g", "i", "w"].map((name) => ts.factory.createIdentifier(name)))));
        photoHooks++;
        return ts.factory.updateFunctionDeclaration(visited, visited.modifiers,
          visited.asteriskToken, visited.name, visited.typeParameters, visited.parameters,
          visited.type, ts.factory.updateBlock(visited.body, statements));
      }
      if (ts.isObjectLiteralExpression(node)) {
        const cls = property(node, "className"), children = property(node, "children");
        if (cls && children && ["ul-zoom", "ul-photo-zoom"].includes(value(cls.initializer))
          && ts.isArrayLiteralExpression(children.initializer)) {
          const order = value(cls.initializer) === "ul-zoom"
            ? ["Zoom utility map out", "Zoom utility map in", "Reset utility map zoom"]
            : ["Zoom out photo", "Zoom in photo", "Fit photo"];
          const elements = [...children.initializer.elements];
          const slots = elements.map((e, i) => order.includes(label(e)) ? i : -1).filter((i) => i >= 0);
          if (slots.length !== 3) throw new Error("Unexpected zoom controls");
          const controls = slots.map((i) => elements[i]).sort((a, b) =>
            order.indexOf(label(a)) - order.indexOf(label(b)));
          slots.forEach((slot, i) => { elements[slot] = controls[i]; });
          const updated = ts.factory.updatePropertyAssignment(children, children.name,
            ts.factory.updateArrayLiteralExpression(children.initializer, elements));
          groups++;
          return ts.factory.updateObjectLiteralExpression(node, node.properties.map((p) => p === children ? updated : p));
        }
      }
      return ts.visitEachChild(node, visit, context);
    };
    return (file) => ts.visitNode(file, visit);
  }]);
  if (groups !== 2) throw new Error(`Expected two zoom groups; found ${groups}`);
  if (photoHooks !== 1) throw new Error(`Expected one photo wheel hook; found ${photoHooks}`);
  const text = printer.printFile(result.transformed[0]);
  result.dispose();
  return `import '../lineups-layout.css';\nimport {usePhotoWheelZoom as __usePhotoWheelZoom} from '../usePhotoWheelZoom';\n${text}`;
}

const files = Object.keys(snapshot.files);
const stem = (name) => name.replace(/-[A-Za-z0-9_-]{8}\.(?:js|css)$/, "");
for (const name of files) {
  let output = snapshot.files[name];
  if (name === manifest.entry) output = entry;
  else if (name.endsWith(".js")) {
    const file = ts.createSourceFile(name, output, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
    const css = files.find((css) => css.endsWith(".css") && stem(css) === stem(name));
    output = (css ? `import './${css}';\n` : "")
      + (name === "Utilities-XNNDiMht.js" ? groupZoomButtons(file) : printer.printFile(file));
  }
  if (check) {
    if (await readFile(join(target, name), "utf8") !== output) throw new Error(`Generated module differs: ${name}`);
  } else await writeFile(join(target, name), output);
}
console.log(`${check ? "Verified" : "Restored"} ${files.length} published modules; two zoom-control groups reordered and one photo-wheel hook added.`);
