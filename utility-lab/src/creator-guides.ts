function guide(details: CreatorGuideDetails): CreatorGuide {
  const source = CREATOR_VIDEO_SOURCES[details.videoId];
  if (!source) throw new Error(`Unknown creator video: ${details.videoId}`);
  const videoUrl = `https://www.youtube.com/watch?v=${source.id}`;
  return applyRegisteredUtilityAnchor<CreatorGuide>({
    id: details.id,
    mapId: details.mapId,
    levelId: details.levelId ?? "main",
    side: details.side,
    type: details.type,
    title: details.title,
    from: details.from,
    target: details.target,
    purpose: "",
    throwType: details.throwType ?? "Follow the video inputs",
    steps: details.steps ?? [
      `Stand at ${details.from === "See video position" ? "the position shown in the video" : details.from}.`,
      "Match the crosshair shown in the video.",
      "Copy the buttons and release timing shown.",
    ],
    x: details.x,
    y: details.y,
    userCreated: false,
    videoUrl,
    videoStart: details.start,
    creator: source.creator,
    source: videoUrl,
    sourceTitle: source.title,
    publishedAt: source.publishedAt,
    sourceCheckedAt: source.checkedAt,
    chapterTitle: details.chapterTitle ?? details.title,
    site: details.site ?? LEGACY_GUIDE_METADATA[details.id]?.site ?? "Other",
    tags: details.tags ?? LEGACY_GUIDE_METADATA[details.id]?.tags ?? [],
    ...(details.captureView ? { captureView: details.captureView } : {}),
    ...(details.sourceNote ? { sourceNote: details.sourceNote } : {}),
  });
}

