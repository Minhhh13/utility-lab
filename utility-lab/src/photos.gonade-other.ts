function siteFor(map: string, target: string): UtilityReference["site"] {
  if (map === "inferno") {
    if (/banana|coffins|ct b|car|oranges|pool|sandbags|^b /i.test(target))
      return "B";
    if (/moto|^a |back a|balcony|pit/i.test(target)) return "A";
    if (/mid/i.test(target)) return "Mid";
  } else {
    if (/^a |fountain/i.test(target)) return "A";
    if (/^b |back b|left b|alley|temple|ebox/i.test(target)) return "B";
    if (/mid|camera|t stairs|rugs|canal/i.test(target)) return "Mid";
  }
  return "Other";
}

function throwType(method: string, click: string): string {
  const action = (
    {
      "Standing throw": "",
      "Jump throw": "Jump",
      "Running throw": "Run",
      "Run + Jump throw": "Run + Jump",
      "Tap + Jump throw": "Tap + Jump",
      "Walking throw": "Walk",
      "Walk + Jump throw": "Walk + Jump",
      "Crouching throw": "Crouch",
      "Crouch + Jump throw": "Crouch + Jump",
    } as Record<string, string>
  )[method];
  if (action === undefined) throw new Error("Unknown source throw: " + method);
  const button =
    click === "Left click"
      ? "LMB"
      : click === "Right click"
        ? "RMB"
        : "Middle click (source label)";
  return [action, button].filter(Boolean).join(" + ");
}

function instructions(row: SourceRow): string[] {
  const [, slug, , from, , , method, click, role, count] = row;
  const button = click === "Left click" ? "LMB" : "RMB";
  const position = "Stand at " + from + " as shown in the first photo.";
  let aim =
    role === "release"
      ? "Match the starting aim; use photo " + count + " as the release point."
      : "Match the crosshair in the final lineup photo.";
  let release = (
    {
      "Standing throw": "Release " + button + " while standing still.",
      "Jump throw": "Jump and release " + button + ".",
      "Running throw":
        "Run with W and release " + button + " at the shown point.",
      "Run + Jump throw":
        "Run with W, jump and release " + button + " at the shown point.",
      "Tap + Jump throw":
        "Tap W, jump and release " + button + " at the shown point.",
      "Walking throw":
        "Hold W + Shift and release " + button + " at the shown point.",
      "Walk + Jump throw":
        "Hold W + Shift, jump and release " + button + " at the shown point.",
      "Crouching throw": "Hold Ctrl and release " + button + ".",
      "Crouch + Jump throw":
        "Hold Ctrl, jump and release " + button + " at the shown point.",
    } as Record<string, string>
  )[method];
  if (click === "Middle click")
    release =
      method === "Running throw"
        ? "Run with W and use the source's Middle click input at the shown point."
        : "Use the source's " +
          method.toLowerCase() +
          " and Middle click input.";
  const steps = [position, aim, release];
  // Actionable prerequisites and aim/release details from each original page.
  if (slug === "anubis-t-stairs-from-a-plat-he")
    steps[1] = "Aim above the wood covering the window, as shown.";
  if (slug === "anubis-mid-doorswindow-from-ruins-molotov") {
    steps[1] = "Keep your crosshair on the shown point while running.";
    steps[2] = "Run with W and release LMB at the second step.";
  }
  if (slug === "anubis-alley-from-b-long-smoke")
    steps[0] = "Wedge into the position shown in the first photo.";
  if (slug === "anubis-t-stairs-from-mid-window-flash")
    steps[1] =
      "Aim to bounce off the left window; use the last photo as the release point.";
  if (slug === "anubis-mid-window-from-ruins-he")
    steps[1] = "Keep your crosshair aligned with the wall mark while running.";
  if (slug === "anubis-back-b-site-from-eboxb-connector-he")
    steps[1] = "Aim between the two clips in the wire, as shown.";
  if (slug === "inferno-coffins-from-car-smoke")
    steps[1] = "Aim above the distinctive line on the wood.";
  if (slug === "inferno-car-from-coffins-flash")
    steps[1] = "Aim at the top of the antenna.";
  if (slug === "inferno-top-banana-from-oranges-he")
    steps[1] = "Aim at the small wall mark shown in the photo.";
  if (slug === "inferno-deep-banana-from-corner-he")
    steps[1] = "Keep aiming at the same point while running.";
  if (slug === "inferno-banana-broom-from-corner-he")
    steps[1] =
      "Keep aiming at the same point; bounce off the yellow-orange wall.";
  return steps;
}

